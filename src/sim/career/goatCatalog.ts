/**
 * All-time legends used by the GOAT ranking (Milestone 11).
 *
 * A curated, static catalog: career totals and per-game rates are the widely cited
 * NBA regular-season figures (playoff totals are not part of a legend's entry), held
 * to whole numbers where the record is settled and to close approximations otherwise.
 * Nothing here is computed at runtime, so the catalog is identical in every career.
 */
export interface GoatLegend {
  id: string;
  name: string;
  /** Career span in the NBA, e.g. "1984-2003". */
  era: string;
  position: string;
  /** NBA championships won. */
  rings: number;
  /** Regular-season MVP awards. */
  mvps: number;
  /** Finals MVP awards. */
  finalsMvps: number;
  /** All-NBA team selections (first, second or third team). */
  allNbaSelections: number;
  careerPoints: number;
  careerRebounds: number;
  careerAssists: number;
  /** Career regular-season points per game. */
  ppg: number;
  rpg: number;
  apg: number;
  /** One line on what makes the career iconic. */
  signatureAccolade: string;
}

